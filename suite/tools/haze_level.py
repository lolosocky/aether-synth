#!/usr/bin/env python3
"""Measures every LGN Haze preset (host_test --levels) and sets its volume so all presets play at the same loudness.
Run from the suite folder with the path to a built LGN_Haze_host: python3 tools/haze_level.py <host> <build dir>"""
import os, subprocess, sys, tempfile
TARGET, PEAK_ROOM = -12.0, 0.5    # LUFS target; peaks may go this far over -1 dBFS into the limiter
here = os.path.dirname(os.path.abspath(__file__))
host, build = sys.argv[1], sys.argv[2]
sys.path.insert(0, here)
for it in range(3):
    out = os.path.join(tempfile.gettempdir(), "haze_levels.txt")
    subprocess.run([host, "--levels", out], check=True, stdout=subprocess.DEVNULL)
    import importlib, haze_volume
    importlib.reload(haze_volume)
    vol = dict(haze_volume.HAZE_VOLUME)
    worst = 0
    for line in open(out):
        key, lufs, peak, cur = line.rstrip("\n").split("\t")
        lufs, peak = float(lufs), float(peak)
        # transient sounds (plucks, short 808s) may push a little further into the limiter so they do not feel quiet
        room = PEAK_ROOM + max(0.0, min(3.0, ((peak - lufs) - 12.0) / 2.0))
        delta = min(TARGET - lufs, -1.0 - peak + room)
        worst = max(worst, abs(delta))
        vol[key] = round(max(-24.0, min(12.0, vol.get(key, 0.0) + delta)), 1)
    with open(os.path.join(here, "haze_volume.py"), "w") as f:
        f.write("# Generated by tools/haze_level.py: per-preset volume offsets (dB) so every preset plays at the same loudness.\nHAZE_VOLUME = {\n")
        for k in sorted(vol): f.write(f"    {k!r}: {vol[k]},\n")
        f.write("}\n")
    print(f"pass {it + 1}: largest correction {worst:.1f} dB")
    subprocess.run([sys.executable, os.path.join(here, "presets.py")], check=True, stdout=subprocess.DEVNULL)
    subprocess.run(["ninja", "-C", build, os.path.basename(host).replace("_host", "_host")], check=True, stdout=subprocess.DEVNULL)
    if worst < 0.5: break
