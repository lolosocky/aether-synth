// Exports the preset library and the source definitions from the browser synth for the plugin, plus reference renders for the port test.
const fs = require('fs'), zlib = require('zlib'), path = require('path');
const WEB = process.env.AETHER_WEB || require('path').join(__dirname, '..', 'web');
const D = require(WEB + '/src/dsp.js')();
const TRIMS = JSON.parse(fs.readFileSync(WEB + '/src/trims.json', 'utf8'));
const LIB = require(WEB + '/src/presets.js')(D, TRIMS);
const out = path.join(__dirname, '..');
const presets = LIB.list.map(p => D.normalizePatch(p));
let maxMods = 0; for (const p of presets) maxMods = Math.max(maxMods, (p.mods || []).length);
console.log('presets', presets.length, 'max mods', maxMods, 'cats', LIB.CATS.length);
const lib = { version: 2, cats: LIB.CATS, defLayer: D.defLayer(1), presets };
const txt = JSON.stringify(lib);
fs.mkdirSync(out + '/resources', { recursive: true });
fs.writeFileSync(out + '/resources/presets.json.gz', zlib.gzipSync(txt, { level: 9 }));
console.log('library', (txt.length / 1e6).toFixed(2), 'MB ->', (fs.statSync(out + '/resources/presets.json.gz').size / 1e3).toFixed(0), 'kB gz');
const srcs = D.SRC_NAMES.map(n => { const d = D.SRC_DEFS[n]; return { name: n, root: d.root, len: d.len, ls: d.ls, le: d.le, flat: d.flat || 0, p: d.p, ev: d.ev }; });
const sj = JSON.stringify(srcs);
// split into chunks: MSVC limits a single string literal to 16 kB
let h = '// Generated by tools/export.js. Do not edit.\n#pragma once\nstatic const char kAetherSourcesJson[] =\n';
for (let i = 0; i < sj.length; i += 4000) h += '  R"AE(' + sj.slice(i, i + 4000) + ')AE"\n';
h += ';\n';
fs.writeFileSync(out + '/src/AetherSourceData.h', h);
if (process.argv[2] === 'ref') {
  // reference renders: every preset, seeded, same notes as the loudness sweep
  const SR = 48000, CHORD = [48, 51, 55, 58];
  const NOTES = { 'Leads': [60], 'Brass & Winds': [60], 'Synth Bass': [36], '808 & Sub': [36], 'Plucks': [60, 67], 'Bells & Mallets': [60, 67], 'Guitars & World': [55, 60, 64], 'Trap & Drill': [60, 67], 'Textures & Noise': [60], 'Sweeps & FX': [60], 'Arps & Sequences': [48, 51, 55] };
  const srcCache = {}, rows = [];
  const dump = (process.argv[3] || '').split(',').filter(Boolean).map(Number);
  fs.mkdirSync(out + '/tests/ref', { recursive: true });
  presets.forEach((p, idx) => {
    const e = new D.Engine(SR);
    for (const L of p.L) if (L.mode === 'gran' || L.mode === 'sample') {
      if (!srcCache[L.src]) srcCache[L.src] = D.renderSource(L.src, SR);
      const s = srcCache[L.src]; if (s) e.msg({ t: 'src', name: L.src, data: s.data, sr: s.sr, root: s.root, ls: s.ls, le: s.le });
    }
    e.msg({ t: 'patch', p });
    D.seed(1000 + idx);
    const notes = NOTES[p.cat] || CHORD, dur = 2.5, offAt = 2;
    for (const n of notes) e.msg({ t: 'on', n, v: 0.8 });
    const N = Math.round(dur * SR), L = new Float32Array(128), R = new Float32Array(128);
    let sum = 0, pk = 0, offDone = false; const head = [];
    const all = dump.includes(idx) ? new Float32Array(N * 2) : null;
    for (let off = 0; off < N; off += 128) {
      if (!offDone && off >= offAt * SR) { for (const n of notes) e.msg({ t: 'off', n }); offDone = true; }
      e.process(L, R, 128);
      for (let i = 0; i < 128 && off + i < N; i++) { sum += (L[i] * L[i] + R[i] * R[i]) * 0.5; pk = Math.max(pk, Math.abs(L[i]), Math.abs(R[i])); if (all) { all[(off + i) * 2] = L[i]; all[(off + i) * 2 + 1] = R[i]; } }
      if (off < 128 * 8) for (let i = 0; i < 128; i += 16) head.push(L[i]);
    }
    if (all) fs.writeFileSync(out + '/tests/ref/' + idx + '.f32', Buffer.from(all.buffer));
    rows.push({ i: idx, name: p.name, cat: p.cat, notes, rms: Math.sqrt(sum / N), pk, head });
  });
  fs.writeFileSync(out + '/tests/ref/ref.json', JSON.stringify(rows));
  fs.writeFileSync(out + '/tests/ref/presets.json', txt);
  console.log('reference rows', rows.length);
}
