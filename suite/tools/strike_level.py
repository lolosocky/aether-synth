#!/usr/bin/env python3
"""Level-matches the LGN Strike sound library: each sound's peak lands on its family's target (kicks loudest, cymbals quietest)."""
import os, subprocess, sys, tempfile
here = os.path.dirname(os.path.abspath(__file__))
exe = os.path.join(tempfile.gettempdir(), "strike_level")
for it in range(3):
    subprocess.run([sys.executable, os.path.join(here, "presets.py")], check=True, stdout=subprocess.DEVNULL)
    subprocess.run(["g++", "-std=c++17", "-O2", "-o", exe, os.path.join(here, "strike_level.cpp")], check=True)
    out = subprocess.run([exe], check=True, capture_output=True, text=True).stdout
    sys.path.insert(0, here)
    try:
        import importlib, strike_levels; importlib.reload(strike_levels); cur = dict(strike_levels.STRIKE_SOUND_LEVEL)
    except ImportError:
        cur = {}
    worst = 0
    for line in out.strip().splitlines():
        name, d = line.split("\t"); d = float(d); worst = max(worst, abs(d))
        cur[name] = round(max(-30.0, min(24.0, cur.get(name, 0.0) + d)), 2)
    with open(os.path.join(here, "strike_levels.py"), "w") as f:
        f.write("# Generated by tools/strike_level.py: per-sound level offsets (dB).\nSTRIKE_SOUND_LEVEL = {\n")
        for k in sorted(cur): f.write(f"    {k!r}: {cur[k]},\n")
        f.write("}\n")
    print(f"pass {it + 1}: largest correction {worst:.2f} dB")
    if worst < 0.1: break
subprocess.run([sys.executable, os.path.join(here, "presets.py")], check=True, stdout=subprocess.DEVNULL)
